static double avg_value(const Point* points, size_t n, int64_t val) {
    if (val <= points[0].id) return points[0].val;
    if (val >= points[n - 1].id) return points[n - 1].val;
    size_t low = 0, high = n - 1;
    while (high - low > 1) {
        size_t mid = (low + high) / 2;
        if (points[mid].id <= val) low = mid;
        else high = mid;
    }
    const auto& p1 = points[low];
    const auto& p2 = points[high];
    return p1.val + (p2.val - p1.val) * (double)(val - p1.id) / (double)(p2.id - p1.id);
}

static int64_t get_known_ts(int64_t uid) {
    size_t low = 0, high = sizeof(KNOWN) / sizeof(KNOWN[0]);
    while (low < high) {
        size_t mid = (low + high) / 2;
        if (KNOWN[mid].id < uid) low = mid + 1;
        else high = mid;
    }
    if (low < sizeof(KNOWN) / sizeof(KNOWN[0]) && KNOWN[low].id == uid) {
        return KNOWN[low].ts;
    }
    return 0;
}

static std::string format_date(int64_t ts) {
    time_t t = (time_t)ts;
    struct tm tm_buf;
#if defined(_WIN32)
    gmtime_s(&tm_buf, &t);
#else
    gmtime_r(&t, &tm_buf);
#endif
    static const char* MONTHS[] = {
        "Янв", "Фев", "Мар", "Апр", "Май", "Июн",
        "Июл", "Авг", "Сен", "Окт", "Ноя", "Дек"
    };
    char buf[64];
    snprintf(buf, sizeof(buf), "%02d %s %04d", tm_buf.tm_mday, MONTHS[tm_buf.tm_mon % 12], tm_buf.tm_year + 1900);
    return std::string(buf);
}

static std::string get_ending(int number, const char* one, const char* two, const char* five) {
    int n = std::abs(number);
    if (n % 10 == 1 && n % 100 != 11) return one;
    if (2 <= n % 10 && n % 10 <= 4 && !(12 <= n % 100 && n % 100 <= 14)) return two;
    return five;
}

static std::string format_age(int64_t reg_ts) {
    time_t now = time(nullptr);
    time_t reg = (time_t)reg_ts;
    struct tm now_tm, reg_tm;
#if defined(_WIN32)
    gmtime_s(&now_tm, &now);
    gmtime_s(&reg_tm, &reg);
#else
    gmtime_r(&now, &now_tm);
    gmtime_r(&reg, &reg_tm);
#endif

    int years = now_tm.tm_year - reg_tm.tm_year;
    int months = now_tm.tm_mon - reg_tm.tm_mon;
    int days = now_tm.tm_mday - reg_tm.tm_mday;

    if (days < 0) {
        months -= 1;
        days += 30;
    }
    if (months < 0) {
        years -= 1;
        months += 12;
    }

    std::string out;
    if (years > 0) {
        out += std::to_string(years) + " " + get_ending(years, "год", "года", "лет");
    }
    if (months > 0) {
        if (!out.empty()) out += ", ";
        out += std::to_string(months) + " " + get_ending(months, "месяц", "месяца", "месяцев");
    }
    if (days > 0 || out.empty()) {
        if (!out.empty()) out += ", ";
        out += std::to_string(days) + " " + get_ending(days, "день", "дня", "дней");
    }
    return out;
}

void cmd_datereg(koto_ctx* ctx, const koto_api* api) {
    if (!api->check_permission(ctx, KOTO_LEVEL_TRUSTED)) return;

    int64_t target_id = 0;
    std::string user_name_str;

    const char* args = api->cmd_args ? api->cmd_args(ctx) : nullptr;
    std::string raw_arg = args ? args : "";
    while (!raw_arg.empty() && (raw_arg.front() == ' ' || raw_arg.front() == '	')) raw_arg.erase(0, 1);
    while (!raw_arg.empty() && (raw_arg.back() == ' ' || raw_arg.back() == '	')) raw_arg.pop_back();

    if (!raw_arg.empty()) {
        if (raw_arg[0] == '@') {
            std::string uname = raw_arg.substr(1);
            if (api->resolve) target_id = api->resolve(ctx, uname.c_str());
            user_name_str = raw_arg;
        } else {
            bool all_digits = true;
            for (char c : raw_arg) {
                if (c < '0' || c > '9') { all_digits = false; break; }
            }
            if (all_digits) {
                target_id = std::strtoll(raw_arg.c_str(), nullptr, 10);
            } else if (api->resolve) {
                target_id = api->resolve(ctx, raw_arg.c_str());
                user_name_str = "@" + raw_arg;
            }
        }
    }

    if (target_id == 0 && api->reply_sender_id) {
        target_id = api->reply_sender_id(ctx);
        char ubuf[128] = {0};
        if (api->user_name && api->user_name(ctx, target_id, ubuf, sizeof(ubuf) - 1) > 0) {
            user_name_str = ubuf;
        }
    }

    if (target_id == 0 && api->sender_id) {
        target_id = api->sender_id(ctx);
        char ubuf[128] = {0};
        if (api->user_name && api->user_name(ctx, target_id, ubuf, sizeof(ubuf) - 1) > 0) {
            user_name_str = ubuf;
        }
    }

    if (target_id <= 0) {
        api->c_reset(ctx);
        api->c_fmt(ctx, "❌ Ответьте на сообщение пользователя или укажите ID / @username!", KOTO_ENT_BOLD);
        if (api->is_outgoing(ctx)) api->c_edit(ctx, 0);
        else api->c_reply(ctx, 0);
        return;
    }

    // Расчет даты
    int64_t known = get_known_ts(target_id);
    double raw_ts = known ? (double)known : avg_value(ANCHORS, sizeof(ANCHORS)/sizeof(ANCHORS[0]), target_id);
    int64_t now_ts = (int64_t)time(nullptr);
    if (raw_ts < MINIMUM_TS) raw_ts = MINIMUM_TS;
    if (raw_ts > now_ts) raw_ts = now_ts;

    int days = (int)std::ceil(avg_value(UNCERTAINTY, sizeof(UNCERTAINTY)/sizeof(UNCERTAINTY[0]), target_id));
    if (days < 1) days = 1;

    int64_t min_ts = (int64_t)raw_ts - (int64_t)days * 86400LL;
    if (min_ts < MINIMUM_TS) min_ts = MINIMUM_TS;
    int64_t max_ts = (int64_t)raw_ts + (int64_t)days * 86400LL;

    std::string date_str = format_date((int64_t)raw_ts);
    std::string min_date_str = format_date(min_ts);
    std::string max_date_str = format_date(max_ts);
    std::string age_str = format_age((int64_t)raw_ts);
    std::string days_unit = get_ending(days, "день", "дня", "дней");

    api->c_reset(ctx);
    api->c_fmt(ctx, "📅 Возраст Telegram-аккаунта (by kote)", KOTO_ENT_BOLD);
    api->c_text(ctx, "\n\n");

    if (!user_name_str.empty()) {
        api->c_fmt(ctx, user_name_str.c_str(), KOTO_ENT_BOLD);
        api->c_text(ctx, "\n");
    }

    api->c_text(ctx, "🔢 ID: ");
    api->c_fmt(ctx, std::to_string(target_id).c_str(), KOTO_ENT_CODE);
    api->c_text(ctx, "\n🗓 Примерная регистрация: ");
    api->c_fmt(ctx, date_str.c_str(), KOTO_ENT_BOLD);
    api->c_text(ctx, "\n🕔 Примерный возраст: ");
    api->c_fmt(ctx, age_str.c_str(), KOTO_ENT_BOLD);
    api->c_text(ctx, "\n\nℹ️ Диапазон: ");
    api->c_text(ctx, (min_date_str + " — " + max_date_str).c_str());
    api->c_text(ctx, ("\nПогрешность: ±" + std::to_string(days) + " " + days_unit + ".").c_str());

    if (api->is_outgoing(ctx)) api->c_edit(ctx, 0);
    else api->c_reply(ctx, 0);
}

